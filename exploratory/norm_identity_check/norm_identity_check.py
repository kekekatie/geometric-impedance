"""Exact symbolic and numerical verification of the unit-norm conjugacy identity.

Verifies the exact unit-norm conjugacy identity

    |pi_parallel(M_k)| * |pi_perp(M_k)| = 1

for the inflation units of the two canonical aperiodic tilings in this repo:

1. Ammann-Beenker (silver ratio, delta = 1 + sqrt(2)):
   - Exact arithmetic in Z[sqrt(2)] for the Pell convergents 1/1, 3/2, 7/5, 17/12
     generated by (1 + sqrt(2))^k = a_k + b_k * sqrt(2) (k = 1..4).
   - Verifies the Pell norm identity a_k^2 - 2 * b_k^2 = (-1)^k = +/-1.
   - Verifies (1 + sqrt(2))^k * (sqrt(2) - 1)^k = 1 both symbolically and
     numerically (50-digit Decimal and IEEE-754 float).
   - Prints the first four memory quanta (sqrt(2) - 1)^k for k = 1..4.

2. Penrose / Fibonacci (golden ratio, phi = (1 + sqrt(5)) / 2):
   - Exact arithmetic in Z[phi] for the Fibonacci/Cassini convergents
     1/1, 2/1, 3/2, 5/3 (F_{n+1} / F_n for n = 1..4).
   - Verifies the Cassini identity F_{n+1} * F_{n-1} - F_n^2 = (-1)^n = +/-1,
     which equals the algebraic norm N(phi^n) = phi^n * phi_bar^n.
   - Verifies |phi^m| * |phi_bar^m| = phi^m * phi^(-m) = 1 both symbolically
     and numerically for the convergent powers and memory-quanta powers m = k + 2.
   - Prints the first four memory quanta phi^(-(k+2)) for k = 1..4.

Standalone script using only the Python standard library.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, getcontext
import math


# High-precision numerical context for Decimal checks
getcontext().prec = 50


@dataclass(frozen=True)
class ZSqrt2:
    """Exact element a + b*sqrt(2) in the ring Z[sqrt(2)]."""

    a: int
    b: int

    def __mul__(self, other: ZSqrt2) -> ZSqrt2:
        return ZSqrt2(
            self.a * other.a + 2 * self.b * other.b,
            self.a * other.b + self.b * other.a,
        )

    def __pow__(self, n: int) -> ZSqrt2:
        if n < 0:
            raise ValueError("Exponent must be non-negative.")
        result = ZSqrt2(1, 0)
        base = self
        exp = n
        while exp > 0:
            if exp & 1:
                result = result * base
            base = base * base
            exp >>= 1
        return result

    @property
    def conjugate(self) -> ZSqrt2:
        """Galois conjugate a - b*sqrt(2) (perpendicular-space projection)."""
        return ZSqrt2(self.a, -self.b)

    @property
    def norm(self) -> int:
        """Algebraic norm N(a + b*sqrt(2)) = a^2 - 2*b^2."""
        return self.a * self.a - 2 * self.b * self.b

    def to_decimal(self) -> Decimal:
        sqrt2 = Decimal(2).sqrt()
        return Decimal(self.a) + Decimal(self.b) * sqrt2

    def to_float(self) -> float:
        return self.a + self.b * math.sqrt(2.0)

    def __str__(self) -> str:
        sign = "+" if self.b >= 0 else "-"
        return f"{self.a} {sign} {abs(self.b)}*sqrt(2)"


@dataclass(frozen=True)
class ZPhi:
    """Exact element p + q*phi in the ring Z[phi], where phi^2 = phi + 1."""

    p: int
    q: int

    def __mul__(self, other: ZPhi) -> ZPhi:
        # (p + q*phi)(r + s*phi) = pr + (ps + qr)*phi + qs*(phi + 1)
        return ZPhi(
            self.p * other.p + self.q * other.q,
            self.p * other.q + self.q * other.p + self.q * other.q,
        )

    def __pow__(self, n: int) -> ZPhi:
        if n < 0:
            raise ValueError("Exponent must be non-negative.")
        result = ZPhi(1, 0)
        base = self
        exp = n
        while exp > 0:
            if exp & 1:
                result = result * base
            base = base * base
            exp >>= 1
        return result

    @property
    def conjugate(self) -> ZPhi:
        """Galois conjugate under phi -> phi_bar = 1 - phi = -phi^(-1)."""
        # p + q*(1 - phi) = (p + q) - q*phi
        return ZPhi(self.p + self.q, -self.q)

    @property
    def norm(self) -> int:
        """Algebraic norm N(p + q*phi) = p^2 + p*q - q^2."""
        return self.p * self.p + self.p * self.q - self.q * self.q

    def to_decimal(self) -> Decimal:
        phi = (Decimal(1) + Decimal(5).sqrt()) / Decimal(2)
        return Decimal(self.p) + Decimal(self.q) * phi

    def to_float(self) -> float:
        phi = (1.0 + math.sqrt(5.0)) / 2.0
        return self.p + self.q * phi

    def __str__(self) -> str:
        sign = "+" if self.q >= 0 else "-"
        return f"{self.p} {sign} {abs(self.q)}*phi"


def fibonacci(n: int) -> int:
    """Return the n-th Fibonacci number with F_0 = 0, F_1 = 1."""
    if n < 0:
        raise ValueError("n must be non-negative.")
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def verify_ammann_beenker() -> None:
    """Verify unit-norm conjugacy and Pell identity for Ammann-Beenker."""
    expected_convergents = [(1, 1), (3, 2), (7, 5), (17, 12)]
    delta = ZSqrt2(1, 1)  # 1 + sqrt(2)
    delta_inv = ZSqrt2(-1, 1)  # sqrt(2) - 1

    # Symbolic base check: (1 + sqrt(2)) * (sqrt(2) - 1) == 1
    assert delta * delta_inv == ZSqrt2(1, 0), "Base silver-ratio product != 1"

    print("=== Ammann-Beenker (Silver Ratio / Pell Convergents) ===")
    quanta: list[tuple[int, ZSqrt2, Decimal]] = []

    for k, (exp_a, exp_b) in enumerate(expected_convergents, start=1):
        pi_par = delta**k
        pi_perp = pi_par.conjugate  # (1 - sqrt(2))^k = (-1)^k * (sqrt(2) - 1)^k
        quantum = delta_inv**k  # (sqrt(2) - 1)^k = |pi_perp|

        # 1. Convergent match: (1 + sqrt(2))^k = a_k + b_k*sqrt(2)
        assert (pi_par.a, pi_par.b) == (exp_a, exp_b), (
            f"k={k}: got {(pi_par.a, pi_par.b)}, expected {(exp_a, exp_b)}"
        )

        # 2. Exact Pell identity: a^2 - 2*b^2 = (-1)^k = +/-1
        pell_norm = pi_par.a**2 - 2 * pi_par.b**2
        expected_sign = (-1) ** k
        assert pell_norm == expected_sign, f"k={k}: Pell norm {pell_norm} != {expected_sign}"
        assert abs(pell_norm) == 1

        # 3. Exact symbolic conjugacy product: pi_par * pi_perp = (-1)^k and pi_par * quantum = 1
        assert pi_par * pi_perp == ZSqrt2(expected_sign, 0)
        assert pi_par * quantum == ZSqrt2(1, 0)

        # 4. High-precision Decimal & float verification of |pi_par| * |pi_perp| = 1
        dec_prod = abs(pi_par.to_decimal()) * abs(pi_perp.to_decimal())
        assert abs(dec_prod - Decimal(1)) < Decimal("1e-45"), (
            f"k={k}: Decimal product mismatch: {dec_prod}"
        )
        # Note: a_k - b_k*sqrt(2) undergoes mild float64 cancellation for larger k
        flt_prod = abs(pi_par.to_float()) * abs(pi_perp.to_float())
        assert math.isclose(flt_prod, 1.0, rel_tol=1e-12, abs_tol=1e-12), (
            f"k={k}: float product mismatch: {flt_prod}"
        )
        direct_flt_prod = ((1.0 + math.sqrt(2.0)) ** k) * ((math.sqrt(2.0) - 1.0) ** k)
        assert math.isclose(direct_flt_prod, 1.0, rel_tol=1e-14, abs_tol=1e-14), (
            f"k={k}: direct float product mismatch: {direct_flt_prod}"
        )
        assert abs(quantum.to_decimal() - abs(pi_perp.to_decimal())) < Decimal("1e-45")

        quanta.append((k, quantum, quantum.to_decimal()))
        print(
            f"  k={k}: convergent {pi_par.a}/{pi_par.b}, "
            f"a^2 - 2b^2 = {pell_norm:+d}, "
            f"|pi_par|*|pi_perp| = {dec_prod:.15f}"
        )

    print("  First four memory quanta (sqrt(2) - 1)^k:")
    for k, q_sym, q_dec in quanta:
        print(f"    k={k}: (sqrt(2) - 1)^{k} = {q_sym} ~= {q_dec:.16f}")
    print()


def verify_penrose_fibonacci() -> None:
    """Verify unit-norm conjugacy and Cassini identity for Penrose / Fibonacci."""
    expected_convergents = [(1, 1), (2, 1), (3, 2), (5, 3)]
    phi = ZPhi(0, 1)  # phi
    phi_inv = ZPhi(-1, 1)  # phi^(-1) = phi - 1 = |phi_bar|

    # Symbolic base check: phi * phi^(-1) == 1 and phi * phi_bar == -1
    assert phi * phi_inv == ZPhi(1, 0), "Base golden-ratio product != 1"
    assert phi * phi.conjugate == ZPhi(-1, 0), "Base golden-ratio norm != -1"

    print("=== Penrose / Fibonacci (Golden Ratio / Cassini Convergents) ===")
    for n, (exp_num, exp_den) in enumerate(expected_convergents, start=1):
        f_prev = fibonacci(n - 1)
        f_curr = fibonacci(n)
        f_next = fibonacci(n + 1)

        # 1. Convergent match: F_{n+1} / F_n
        assert (f_next, f_curr) == (exp_num, exp_den), (
            f"n={n}: got {f_next}/{f_curr}, expected {exp_num}/{exp_den}"
        )

        # 2. Exact Cassini identity: F_{n+1}*F_{n-1} - F_n^2 = (-1)^n = +/-1
        cassini = f_next * f_prev - f_curr * f_curr
        expected_sign = (-1) ** n
        assert cassini == expected_sign, f"n={n}: Cassini {cassini} != {expected_sign}"
        assert abs(cassini) == 1

        # 3. Corresponding phi conjugacy: phi^n = F_{n-1} + F_n*phi, N(phi^n) = Cassini
        pi_par = phi**n
        pi_perp = pi_par.conjugate  # phi_bar^n = (-1)^n * phi^(-n)
        assert (pi_par.p, pi_par.q) == (f_prev, f_curr)
        assert pi_par.norm == cassini
        assert pi_par * pi_perp == ZPhi(expected_sign, 0)
        assert pi_par * (phi_inv**n) == ZPhi(1, 0)

        # 4. High-precision Decimal & float verification of |pi_par| * |pi_perp| = 1
        dec_prod = abs(pi_par.to_decimal()) * abs(pi_perp.to_decimal())
        assert abs(dec_prod - Decimal(1)) < Decimal("1e-45"), (
            f"n={n}: Decimal product mismatch: {dec_prod}"
        )
        flt_prod = abs(pi_par.to_float()) * abs(pi_perp.to_float())
        assert math.isclose(flt_prod, 1.0, rel_tol=1e-12, abs_tol=1e-12), (
            f"n={n}: float product mismatch: {flt_prod}"
        )
        phi_flt = (1.0 + math.sqrt(5.0)) / 2.0
        direct_flt_prod = (phi_flt**n) * ((phi_flt - 1.0) ** n)
        assert math.isclose(direct_flt_prod, 1.0, rel_tol=1e-14, abs_tol=1e-14), (
            f"n={n}: direct float product mismatch: {direct_flt_prod}"
        )

        print(
            f"  n={n}: convergent {f_next}/{f_curr}, "
            f"F_{{n+1}}*F_{{n-1}} - F_n^2 = {cassini:+d}, "
            f"|pi_par|*|pi_perp| = {dec_prod:.15f}"
        )

    print("  First four memory quanta phi^(-(k+2)):")
    for k in range(1, 5):
        m = k + 2
        pi_par = phi**m
        pi_perp = pi_par.conjugate
        quantum = phi_inv**m  # phi^(-(k+2)) = |pi_perp(M_{k+2})|

        assert pi_par * quantum == ZPhi(1, 0)
        assert pi_par * pi_perp == ZPhi((-1) ** m, 0)

        q_dec = quantum.to_decimal()
        dec_prod = abs(pi_par.to_decimal()) * q_dec
        assert abs(dec_prod - Decimal(1)) < Decimal("1e-45")
        assert abs(q_dec - abs(pi_perp.to_decimal())) < Decimal("1e-45")

        print(f"    k={k}: phi^(-{m}) = {quantum} ~= {q_dec:.16f}")
    print()


def main() -> None:
    verify_ammann_beenker()
    verify_penrose_fibonacci()
    print("All unit-norm conjugacy assertions passed.")


if __name__ == "__main__":
    main()
